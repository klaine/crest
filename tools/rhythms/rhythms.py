#!/usr/bin/env python3
"""Generates src/dsp/rhythms_gen.h: the 33 arpeggiator rhythm patterns (plan/09).

Pattern 0 plays every step. The rest are Crest's own: Euclidean rhythms of 5..16 steps plus a few hand-made
grooves. (Peak's pattern data is not public, so these are musical equivalents, not copies.)
Each entry is (bit mask with step 0 as the lowest bit, length in steps).
"""
import os


def euclid(k, n):
    """Bjorklund via the bucket method; returns n booleans, starting on a hit."""
    out, b = [], 0
    for i in range(n):
        b += k
        if b >= n:
            b -= n
            out.append(True)
        else:
            out.append(False)
    # rotate so the first step is a hit
    j = out.index(True)
    return out[j:] + out[:j]


def mask(bits):
    return sum(1 << i for i, v in enumerate(bits) if v)


def hand(s):
    s = s.replace(" ", "")
    return [c == "x" for c in s]


PATTERNS = [(0xFFFF, 16)]
SPEC = [("e", 8, 16), ("e", 6, 16), ("e", 5, 16), ("e", 4, 16), ("e", 3, 16), ("e", 7, 16), ("e", 9, 16),
        ("e", 10, 16), ("e", 11, 16), ("e", 12, 16), ("e", 13, 16), ("e", 2, 16), ("e", 5, 8), ("e", 3, 8),
        ("e", 7, 8), ("e", 4, 7), ("e", 3, 7), ("e", 3, 5), ("e", 2, 5), ("e", 5, 12), ("e", 7, 12),
        ("e", 3, 12),
        ("h", "x.xx x.xx x.xx x.xx"), ("h", "x..x ..x. x..x ..x."), ("h", "xxx. xxx. xxx. xxx."),
        ("h", "x.x. xx.x x.x. xx.x"), ("h", "x... x.xx x... x.x."), ("h", "xx.x xx.x xx.x xx.."),
        ("h", ".x.x .x.x .x.x .x.x"), ("h", "x.xx .xx. x.xx .xx."), ("h", "xxxx .... xxxx ...."),
        ("h", "x.x. .x.x ..x. x..x")]
for kind, a, *rest in SPEC:
    bits = euclid(a, rest[0]) if kind == "e" else hand(a)
    PATTERNS.append((mask(bits), len(bits)))
assert len(PATTERNS) == 33, len(PATTERNS)


def main():
    root = os.path.join(os.path.dirname(__file__), "..", "..")
    lines = ["/* Generated by tools/rhythms/rhythms.py: do not edit. */", "#ifndef CREST_RHYTHMS_GEN_H",
             "#define CREST_RHYTHMS_GEN_H", "", "#define ARP_RHYTHMS 33", "",
             "/* bit i of mask = step i plays; len = pattern length in steps */",
             "static const struct { unsigned short mask; unsigned char len; } ARP_RHYTHM[ARP_RHYTHMS] = {"]
    for m, n in PATTERNS:
        lines.append("    {0x%04X, %d}," % (m, n))
    lines += ["};", "", "#endif", ""]
    with open(os.path.join(root, "src", "dsp", "rhythms_gen.h"), "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
